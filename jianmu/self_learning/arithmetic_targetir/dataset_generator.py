import json
import random
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from jianmu.self_learning.arithmetic_targetir.expression_oracle import UnsupportedReason, parse_controlled_expression


DEFAULT_SEED = 20260518
DEFAULT_TRAIN_SIZE = 5000
DEFAULT_EVAL_SIZE = 1000

DATASET_DIR = Path("datasets/v0_5_8")
TRAIN_PATH = DATASET_DIR / "jianmu_arithmetic_targetir_train.jsonl"
EVAL_PATH = DATASET_DIR / "jianmu_arithmetic_targetir_eval.jsonl"
REPORT_PATH = DATASET_DIR / "jianmu_arithmetic_targetir_report.md"

ATOMIC_EXPERTS = [
    "ArithmeticExpressionExpert",
    "PrecedenceResolverExpert",
    "PrintExpert",
    "ConsistencyCheckExpert",
]

CHINESE_NUMBERS = {
    0: "零",
    1: "一",
    2: "二",
    3: "三",
    4: "四",
    5: "五",
    6: "六",
    7: "七",
    8: "八",
    9: "九",
    10: "十",
}


@dataclass(frozen=True)
class ExpressionSpec:
    expr: str
    expression_form: str
    structure_label: str
    template_group: str


def ensure_arithmetic_targetir_dataset(
    train_size: int = DEFAULT_TRAIN_SIZE,
    eval_size: int = DEFAULT_EVAL_SIZE,
    seed: int = DEFAULT_SEED,
):
    DATASET_DIR.mkdir(parents=True, exist_ok=True)
    train, eval_samples = build_dataset(train_size=train_size, eval_size=eval_size, seed=seed)
    _write_jsonl(TRAIN_PATH, train)
    _write_jsonl(EVAL_PATH, eval_samples)
    REPORT_PATH.write_text(build_report(train, eval_samples, seed), encoding="utf-8")
    return train, eval_samples


def build_dataset(
    train_size: int = DEFAULT_TRAIN_SIZE,
    eval_size: int = DEFAULT_EVAL_SIZE,
    seed: int = DEFAULT_SEED,
) -> Tuple[List[Dict], List[Dict]]:
    rng = random.Random(seed)
    train = _build_split("train", train_size, 1, rng, eval_mode=False)
    eval_samples = _build_split("eval", eval_size, train_size + 1, rng, eval_mode=True)
    return train, eval_samples


def build_report(train: List[Dict], eval_samples: List[Dict], seed: int) -> str:
    all_samples = train + eval_samples
    supported = sum(1 for sample in all_samples if sample["supported"])
    forms = Counter(sample["expression_form"] for sample in all_samples)
    structures = Counter(sample["structure_label"] for sample in all_samples)
    unsupported = Counter(sample.get("unsupported_reason") for sample in all_samples if not sample["supported"])
    eval_only_templates = sum(1 for sample in eval_samples if str(sample["template_id"]).startswith("eval_"))
    lines = [
        "# JianMu v0.5.8 Arithmetic TargetIR Dataset",
        "",
        "- version: v0.5.8-development",
        f"- seed: {seed}",
        f"- train samples: {len(train)}",
        f"- eval samples: {len(eval_samples)}",
        f"- total samples: {len(all_samples)}",
        f"- supported samples: {supported}",
        f"- unsupported samples: {len(all_samples) - supported}",
        f"- eval-only templates: {eval_only_templates}",
        "",
        "## Expression Form Counts",
        "",
    ]
    for key, value in sorted(forms.items()):
        lines.append(f"- {key}: {value}")
    lines.extend(["", "## Structure Label Counts", ""])
    for key, value in sorted(structures.items()):
        lines.append(f"- {key}: {value}")
    lines.extend(["", "## Unsupported Reason Counts", ""])
    for key, value in sorted(unsupported.items()):
        lines.append(f"- {key}: {value}")
    lines.extend(
        [
            "",
            "## Notes",
            "",
            "- Ground truth is generated by a deterministic expression oracle.",
            "- The target is canonical Arithmetic TargetIR, not C source text.",
            "- Unsupported division includes non-exact integer division and division by zero.",
            "- This dataset is a controlled Chinese-first arithmetic TargetIR benchmark seed.",
            "",
            "## Non-Claims",
            "",
            "- This dataset does not prove general learned routing.",
            "- This dataset does not prove general program synthesis.",
            "- This dataset does not prove natural-language generalization.",
            "- This dataset does not prove AGI or hardware BPU implementation.",
        ]
    )
    return "\n".join(lines) + "\n"


def _build_split(split: str, size: int, start_id: int, rng: random.Random, eval_mode: bool) -> List[Dict]:
    supported_target = round(size * 0.85)
    supported_counts = {
        "addition_only": round(supported_target * 0.20),
        "subtraction": round(supported_target * 0.15),
        "multiplication": round(supported_target * 0.20),
        "exact_division": round(supported_target * 0.15),
        "mixed_precedence": round(supported_target * 0.20),
    }
    supported_counts["parentheses"] = supported_target - sum(supported_counts.values())
    unsupported_count = size - supported_target

    specs: List[Optional[ExpressionSpec]] = []
    for form, count in supported_counts.items():
        for _ in range(count):
            specs.append(_make_supported_spec(form, rng, eval_mode))
    for _ in range(unsupported_count):
        specs.append(None)
    rng.shuffle(specs)

    samples: List[Dict] = []
    seen_inputs = set()
    for offset, spec in enumerate(specs):
        sample_id = f"arith-{start_id + offset:06d}"
        if spec is None:
            sample = _make_unsupported_sample(sample_id, split, rng, eval_mode)
        else:
            sample = _make_supported_sample(sample_id, split, spec, rng, eval_mode)
        while sample["input_text"] in seen_inputs:
            if spec is None:
                sample = _make_unsupported_sample(sample_id, split, rng, eval_mode)
            else:
                sample = _make_supported_sample(sample_id, split, spec, rng, eval_mode)
        seen_inputs.add(sample["input_text"])
        samples.append(sample)
    return samples


def _make_supported_spec(form: str, rng: random.Random, eval_mode: bool) -> ExpressionSpec:
    lo, hi = (11, 20) if eval_mode and rng.random() < 0.35 else (1, 10)
    a = rng.randint(lo, hi)
    b = rng.randint(1, 10)
    c = rng.randint(1, 10)
    if rng.random() < 0.12:
        a = -rng.randint(1, 5)
    if form == "addition_only":
        if rng.random() < 0.35:
            return ExpressionSpec(f"{_num(a, rng)}+{_num(b, rng)}+{_num(c, rng)}", form, "ADD_REDUCE", "addition_only")
        return ExpressionSpec(f"{_num(a, rng)}+{_num(b, rng)}", form, "BIN_ADD", "addition_only")
    if form == "subtraction":
        return ExpressionSpec(f"{_num(a, rng)}-{_num(b, rng)}", form, "BIN_SUB", "subtraction")
    if form == "multiplication":
        return ExpressionSpec(f"{_num(a, rng)}*{_num(b, rng)}", form, "BIN_MUL", "multiplication")
    if form == "exact_division":
        divisor = rng.randint(1, 10)
        quotient = rng.randint(1, 10)
        dividend = divisor * quotient
        return ExpressionSpec(f"{_num(dividend, rng)}路/{_num(divisor, rng)}".replace("路", ""), form, "BIN_DIV", "exact_division")
    if form == "mixed_precedence":
        options = [
            ExpressionSpec(f"{_num(a, rng)}+{_num(b, rng)}*{_num(c, rng)}", form, "ADD_THEN_MUL", "mixed_precedence"),
            ExpressionSpec(f"{_num(a, rng)}*{_num(b, rng)}+{_num(c, rng)}", form, "MUL_THEN_ADD", "mixed_precedence"),
            ExpressionSpec(f"{_num(a, rng)}-{_num(b, rng)}*{_num(c, rng)}", form, "SUB_THEN_MUL", "mixed_precedence"),
        ]
        return rng.choice(options)
    if form == "parentheses":
        if rng.random() < 0.5:
            return ExpressionSpec(f"({_num(a, rng)}+{_num(b, rng)})*{_num(c, rng)}", form, "PAREN_ADD_THEN_MUL", "parentheses")
        divisor = rng.randint(1, 5)
        quotient = rng.randint(1, 8)
        left = divisor * quotient + b
        return ExpressionSpec(f"({_num(left, rng)}-{_num(b, rng)})/{_num(divisor, rng)}", form, "PAREN_SUB_THEN_DIV", "parentheses")
    raise ValueError(f"unsupported form: {form}")


def _make_supported_sample(sample_id: str, split: str, spec: ExpressionSpec, rng: random.Random, eval_mode: bool) -> Dict:
    input_text, template_id = _wrap_expression(spec.expr, rng, eval_mode)
    parsed = parse_controlled_expression(input_text)
    if isinstance(parsed, UnsupportedReason):
        raise ValueError(f"generated supported expression failed oracle parse: {input_text}: {parsed}")
    numbers = [token["value"] for token in parsed.program_ir_tokens() if token["type"] == "LITERAL_INT"]
    operators = [token["type"] for token in parsed.program_ir_tokens() if token["type"] != "LITERAL_INT"]
    return {
        "sample_id": sample_id,
        "split": split,
        "input_text": input_text,
        "language": "zh-CN",
        "supported": True,
        "unsupported_reason": None,
        "expression_form": spec.expression_form,
        "structure_label": spec.structure_label,
        "target_ir": parsed.to_dict(),
        "slots": {
            "numbers": numbers,
            "operators": operators,
            "has_parentheses": "(" in spec.expr or "（" in spec.expr,
        },
        "program_ir_tokens": parsed.program_ir_tokens(),
        "atomic_experts": ATOMIC_EXPERTS,
        "expected_output_provenance": "oracle_expression",
        "template_id": template_id,
    }


def _make_unsupported_sample(sample_id: str, split: str, rng: random.Random, eval_mode: bool) -> Dict:
    reason, base = rng.choice(
        [
            ("division_not_exact", "写一个 C 程序输出 {a}/{b}"),
            ("division_by_zero", "printf 输出 {a}/0"),
            ("invalid_expression", "写一个 C 程序输出 {a}++{b}"),
            ("english_natural_language", "calculate {a} plus {b}"),
            ("unrelated_task", "写一首关于编译器的小诗，编号 {a} 和 {b}"),
        ]
    )
    a = rng.randint(1, 99 if eval_mode else 50)
    b = rng.choice([2, 3, 4, 5, 6, 7])
    if reason == "division_not_exact":
        while a % b == 0:
            a += 1
    text = base.format(a=a, b=b)
    if eval_mode and rng.random() < 0.35:
        text = f"请帮我算一下 {a}/0 的结果" if reason == "division_by_zero" else text
    template_id = ("eval_" if eval_mode else "train_") + f"unsupported_{reason}"
    return {
        "sample_id": sample_id,
        "split": split,
        "input_text": text,
        "language": "zh-CN" if reason != "english_natural_language" else "en",
        "supported": False,
        "unsupported_reason": reason,
        "expression_form": "unsupported",
        "structure_label": "UNSUPPORTED",
        "target_ir": None,
        "slots": {
            "numbers": [],
            "operators": [],
            "has_parentheses": False,
        },
        "program_ir_tokens": [],
        "atomic_experts": [],
        "expected_output": None,
        "expected_output_provenance": "none",
        "template_id": template_id,
    }


def _wrap_expression(expr: str, rng: random.Random, eval_mode: bool) -> Tuple[str, str]:
    templates = [
        ("写一个 C 程序输出 {expr}", "arith_cn_write_c"),
        ("写程序计算 {expr} 的结果", "arith_cn_compute"),
        ("用 printf 输出 {expr}", "arith_cn_printf"),
        ("定义 int main，然后输出 {expr}", "arith_cn_int_main"),
        ("请输出：{expr}", "arith_cn_colon"),
    ]
    eval_templates = [
        ("生成 C 程序，让 printf 打印 {expr}", "eval_arith_printf_print"),
        ("main 里计算（{expr}）并输出", "eval_arith_main_parenthetical"),
        ("把 {expr} 作为整数表达式输出", "eval_arith_int_expr"),
    ]
    template, template_id = rng.choice(eval_templates if eval_mode and rng.random() < 0.55 else templates)
    spaced_expr = _maybe_space_expression(expr, rng)
    return template.format(expr=spaced_expr), template_id


def _maybe_space_expression(expr: str, rng: random.Random) -> str:
    if rng.random() >= 0.25:
        return expr
    return expr.replace("+", " + ").replace("-", " - ").replace("*", " * ").replace("/", " / ")


def _num(value: int, rng: random.Random) -> str:
    if value < 0:
        magnitude = abs(value)
        if magnitude in CHINESE_NUMBERS and rng.random() < 0.45:
            return "负" + CHINESE_NUMBERS[magnitude]
        return str(value)
    if value in CHINESE_NUMBERS and value != 0 and rng.random() < 0.28:
        return CHINESE_NUMBERS[value]
    return str(value)


def _write_jsonl(path: Path, samples: List[Dict]):
    path.write_text(
        "".join(json.dumps(sample, ensure_ascii=False, sort_keys=True) + "\n" for sample in samples),
        encoding="utf-8",
    )


